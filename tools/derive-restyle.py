#!/usr/bin/env python3
"""Derive anchored source patches from a restyled DYE2 plugin.js.

    python3 tools/derive-restyle.py <upstream-checkout> <baseline-plugin.js> <restyled-plugin.js> <out-dir>

Both plugin.js files are built (not minified) bundles, so template-literal text appears verbatim.
The bundle is split into regions (`//#region src/...`), each diff is mapped back to its source file,
and widened with neighbouring lines until the anchor is unique in that file. Output:

  restyle.rules.json   [{file, find, replace}]  applied by patches/dye2/03-restyle.mjs
  bp-slider.css        the slider stylesheet  (a string constant in the restyled bundle)
  bp-slider.js         the slider script      (a string constant in the restyled bundle)
  manual.txt           edits that could not be mapped automatically
"""
import difflib
import json
import re
import subprocess
import sys
from pathlib import Path

checkout, base_js, new_js, out_dir = sys.argv[1:5]
checkout = Path(checkout)
out_dir = Path(out_dir)
out_dir.mkdir(parents=True, exist_ok=True)

a = Path(base_js).read_text().split("\n")
b = Path(new_js).read_text().split("\n")

# Region name for every baseline line.
region_at = []
current = None
for line in a:
    m = re.match(r"\t//#region (.+)$", line)
    if m:
        current = m.group(1)
    region_at.append(current)
    if re.match(r"\t//#endregion", line):
        current = None

sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
ops = [list(o) for o in sm.get_opcodes()]

# Merge non-equal ops separated by fewer than 2 equal lines.
merged = []
for op in ops:
    if op[0] == "equal":
        merged.append(op)
        continue
    if len(merged) >= 2 and merged[-1][0] == "equal" and (merged[-1][2] - merged[-1][1]) < 2 and merged[-2][0] != "equal":
        eq = merged.pop()
        prev = merged.pop()
        merged.append(["replace", prev[1], op[2], prev[3], op[4]])
    elif merged and merged[-1][0] != "equal":
        prev = merged.pop()
        merged.append(["replace", prev[1], op[2], prev[3], op[4]])
    else:
        merged.append(op)

source_cache = {}


def source(path):
    if path not in source_cache:
        source_cache[path] = (checkout / "dye2-plugin" / path).read_text()
    return source_cache[path]


def strip_tab(lines):
    return [l[1:] if l.startswith("\t") else l for l in lines]


rules = []
manual = []
for tag, i1, i2, j1, j2 in merged:
    if tag == "equal":
        continue
    region = region_at[i1] if i1 < len(a) else None
    if region is None and i1 > 0:
        region = region_at[i1 - 1]
    if region and region.startswith("src/styles/tailwind.generated"):
        continue  # regenerated by the build
    if not region or not region.startswith("src/"):
        manual.append(f"no source region for a[{i1}:{i2}]")
        continue
    path = region
    text = source(path)
    old, new = a[i1:i2], b[j1:j2]
    lo, hi = i1, i2  # context window in baseline coordinates
    found = None
    for variant in (0, 1):
        for _ in range(8):
            ctx_before = a[lo:i1]
            ctx_after = a[i2:hi]
            before = strip_tab(ctx_before) if variant else ctx_before
            after = strip_tab(ctx_after) if variant else ctx_after
            o = strip_tab(old) if variant else old
            n = strip_tab(new) if variant else new
            find = "\n".join(before + o + after)
            replace = "\n".join(before + n + after)
            count = text.count(find) if find else 0
            if count == 1:
                found = (find, replace)
                break
            if count == 0:
                break
            # widen: alternate before / after, staying inside the region
            if (lo > 0 and region_at[lo - 1] == region and (i1 - lo) <= (hi - i2)):
                lo -= 1
            elif hi < len(a) and region_at[hi] == region:
                hi += 1
            else:
                break
        if found:
            break
        lo, hi = i1, i2
    if not found:
        manual.append(f"{path} a[{i1}:{i2}] -> b[{j1}:{j2}]: {old[:2]!r}")
        continue
    rules.append({"file": f"dye2-plugin/{path}", "find": found[0], "replace": found[1]})

(out_dir / "restyle.rules.json").write_text(json.dumps(rules, indent=1) + "\n")
(out_dir / "manual.txt").write_text("\n".join(manual) + "\n")

# The slider assets are string constants in the restyled bundle; evaluate the literals to get the text.
def extract_const(name):
    for line in b:
        m = re.match(rf"\tvar {name} = (.*);$", line)
        if m:
            return json.loads(
                subprocess.check_output(["node", "-e", "process.stdout.write(JSON.stringify(eval(process.argv[1])))", m.group(1)])
            )
    raise SystemExit(f"{name} not found")


(out_dir / "bp-slider.css").write_text(extract_const("bpSliderCss"))
(out_dir / "bp-slider.js").write_text(extract_const("bpSliderScript"))
print(f"{len(rules)} rules, {len(manual)} manual")
for m in manual:
    print("MANUAL:", m)
